// DSA stands for:
// D = Data
// S = Structure
// A = Algorithms

// in simple words: 
// DSA  is the study to organize data effiently and
// solve problems using step-by-step methods.

// Examples : 
// Data Structure           Real-life Example
// Array                    A row of lockers
// Stack                    A stack of plates
// Queue                    People waiting in a ticket  line
// Linked List              Train coaches connected together
// Tree                     Family tree or file system
// Graph                    Google Maps or social networks
// Hash Map                 Dictionary (word -> meaning)


// Algorithm
//An Algorithm is a step-by-step process to solve a problem.