// Topic - Sorting
// - Sorting means arranging data in a specific order, such as
// - ascending or descending order.

//  Ascending Order  -> smallest to largest
// Example - [2,3,4,5,6]

// Descending Order -> largest to smallest
// Example - [10,8,6,4,3,2,1]

// Why do we use sorting ?
// - Sorting makes data easier to search, analyze, and process.

// Types or Sorting
// 1. Bubble Sort
// - Repeatedly compares adjacent elements and 
//  -swaps them if they are in the wrong order.

// Example : [5, 2, 4, 1]
//→ [2, 5, 4, 1]
//→ [2, 4, 5, 1]
//→ [2, 4, 1, 5]

// 2.  Selection Sort 
// -  Finds the smallest element and places
// - it at the correct position.


// 3. Insertion Sort
// -  Takes one element at a time and inserts it into its correct
// - position in the sorted portion.

// 4. Merge Sort
// - Divides the array into smaller parts,
// - sorts them, and then merges them.

// 5. Quick Sort
// - Selects a pivot, partitions the array around it,
// - and recursively sorts the parts.

// 6.  Heap Sort
// - Uses a heap data structure to repeatedly select 
//  - the largest or smallest element.

//  7. Counting Sort
//   - Counts how many times each value occurs.
//  - It is useful when the range of integer values is relatively small.

// 8. Radix Sort
// - Sorts numbers digit by digit, usually from the least
// - significant digit to the most significant digit.

// 9. Bucket Sort
//  - Distributes elements into different buckets,
//   sorts each bucket, and combines them.
